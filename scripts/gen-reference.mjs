#!/usr/bin/env node
// gen-reference.mjs: write the reference pages from inventory/atoms.json.
//
// Reference pages list every value of a kind (every settings key, error code,
// route, flag...) straight from the scan, so they cannot fall behind the code.
// Guide pages explain; these pages are for looking things up. Each row links
// to the guide page of the feature that owns it, once that page exists.
//
// Usage: node scripts/gen-reference.mjs   (run after inventory-scan.mjs)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const { atoms, repos } = JSON.parse(readFileSync(join(root, 'inventory', 'atoms.json'), 'utf8'));
const features = (await import(join(root, 'inventory', 'features.mjs'))).default;
for (const ft of features) ft._re = ft.match.map((p) => new RegExp(p));

const docs = join(root, 'src', 'content', 'docs');
const GENERATED = new Set(['reference/forge-capabilities', 'reference/settings', 'reference/validation-codes', 'reference/enums', 'reference/http-api', 'reference/console-routes', 'reference/templates', 'reference/voice-tools', 'belai/cli-reference', 'belai/tui-commands', 'belai/settings-file']);
const checked = Object.entries(repos).filter(([, s]) => s).map(([r, s]) => `${r}@${s.slice(0, 7)}`);
const short = (repo) => checked.filter((c) => c.startsWith(`${repo}@`));

// The guide page that explains an atom: the first feature that owns it whose
// page is not itself generated and already exists.
function guideFor(a) {
  for (const ft of features) {
    if (GENERATED.has(ft.page)) continue;
    if (ft._re.some((re) => re.test(a.id)) && existsSync(join(docs, `${ft.page}.md`))) return ft;
  }
  return null;
}
// A link to a guide page, or plain text while that page is still to be written.
const pageLink = (page, text) => (existsSync(join(docs, `${page}.md`)) ? `[${text}](/${page}/)` : text);
const link = (ft) => (ft ? `[${ft.title}](/${ft.page}/)` : '');
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').trim();
const code = (s) => (s === undefined || s === null || s === '' ? '' : `\`${String(s).replace(/`/g, '')}\``);
const by = (kind) => atoms.filter((a) => a.kind === kind);
const groupBy = (xs, f) => xs.reduce((m, x) => { const k = f(x); (m[k] ??= []).push(x); return m; }, {});

function write(page, fm, body) {
  const file = join(docs, `${page}.md`);
  mkdirSync(dirname(file), { recursive: true });
  const front = [
    '---',
    `title: ${JSON.stringify(fm.title)}`,
    `description: ${JSON.stringify(fm.description)}`,
    `order: ${fm.order}`,
    ...(fm.nav ? [`nav: ${JSON.stringify(fm.nav)}`] : []),
    'generated: true',
    `checked: [${fm.checked.map((c) => JSON.stringify(c)).join(', ')}]`,
    '---',
    '',
    '<!-- Generated by scripts/gen-reference.mjs from inventory/atoms.json. Do not edit by hand. -->',
    '',
  ].join('\n');
  writeFileSync(file, front + body.trim() + '\n');
}

// ── Settings ────────────────────────────────────────────────────────────────
{
  const sections = groupBy(by('setting'), (a) => (a.value.includes('.') ? a.value.split('.')[0] : 'other'));
  let body = 'Factory settings are one revisioned document per tenant. Change them on the console\'s Factory settings page or with `PUT /v1/factory/settings`. Keys stored on **sandbox** belong to the Pix Sandbox and are edited here for convenience. A key marked **locked** cannot be changed.\n\n';
  body += 'Sections: ' + Object.keys(sections).map((s) => `[${s}](#${s})`).join(' · ') + '\n';
  for (const [sec, rows] of Object.entries(sections)) {
    body += `\n## ${sec}\n\n| Key | Type and values | Default | Stored | Explained in |\n|---|---|---|---|---|\n`;
    for (const a of rows) {
      const d = a.detail ?? {};
      let type = d.type ?? '';
      if (d.values?.length) type = `enum: ${d.values.map(code).join(', ')}`;
      else if (d.min !== undefined || d.max !== undefined) type = `${type} ${d.min ?? ''} to ${d.max ?? ''}`.trim();
      if (!d.values?.length && d.doc && d.doc !== type) type = type ? `${type}. ${d.doc}` : d.doc;
      const def = d.default ?? (d.docDefault ? d.docDefault.replace(/`/g, '') : '');
      body += `| <span id="${a.value}"></span>${code(a.value)} | ${cell(type)} | ${code(def)} | ${cell(d.store)}${d.locked ? ', locked' : ''} | ${link(guideFor(a))} |\n`;
    }
  }
  write('reference/settings', { title: 'Settings', description: `Every key in the factory settings document: ${by('setting').length} keys with type, allowed values, default and where each is stored.`, order: 1, checked: short('vdb-site') }, body);
}

// ── Validation and API error codes ─────────────────────────────────────────
{
  let body = 'Codes the API returns in `issues[].code` when it refuses a request, and the codes a workflow gets when it is validated for publish or a dry run. The message is the one the console shows; `{node}` is replaced with the step\'s name.\n\n| Code | Message | Explained in |\n|---|---|---|\n';
  for (const a of by('code')) body += `| <span id="${a.value}"></span>${code(a.value)} | ${cell(a.detail?.message)} | ${link(guideFor(a))} |\n`;
  write('reference/validation-codes', { title: 'Validation and error codes', nav: 'Error codes', description: `All ${by('code').length} codes the factory API and the workflow validator return, with the message each one carries.`, order: 2, checked: short('vdb-site') }, body);
}

// ── Enumerations ───────────────────────────────────────────────────────────
{
  const sets = groupBy(by('enum'), (a) => a.set);
  let body = 'Every closed list of values in the factory API: node types, trigger kinds, statuses, event kinds and more. Each list is named as it appears in the code, so you can find it in `vdb-site`. Where a list is explained in a guide, the guide is linked.\n';
  for (const [set, rows] of Object.entries(sets).sort(([a], [b]) => a.localeCompare(b))) {
    const ft = guideFor(rows[0]);
    body += `\n### ${set}\n\n${ft ? `Explained in ${link(ft)}. ` : ''}Defined in \`${rows[0].sources[0].replace(/^vdb-site\//, '')}\`.\n\n${rows.map((r) => code(r.value.split('=')[1])).join(', ')}\n`;
  }
  write('reference/enums', { title: 'Enumerations', description: `The ${Object.keys(sets).length} closed value lists in the factory and Belai APIs, with every allowed value.`, order: 3, checked: short('vdb-site') }, body);
}

// ── HTTP API ───────────────────────────────────────────────────────────────
{
  const routes = by('route').map((a) => ({ a, method: a.value.split(' ')[0], path: a.value.split(' ')[1] }));
  const groups = groupBy(routes, (r) => r.path.split('/').slice(0, 4).join('/').replace(/\{[^}]+\}/g, '{…}'));
  let body = 'Every Software Factory, Belai and Pix route the API serves. Routes under `/v1/factory` and `/v1/belai` need a signed-in console session (or an API key) and act on the caller\'s tenant. Internal routes are called by schedulers and the Pix call worker with a signed header, not by people.\n';
  for (const [g, rows] of Object.entries(groups).sort(([a], [b]) => a.localeCompare(b))) {
    body += `\n## ${g}\n\n| Method | Path | Explained in |\n|---|---|---|\n`;
    for (const { a, method, path } of rows.sort((x, y) => x.path.localeCompare(y.path) || x.method.localeCompare(y.method))) body += `| ${method} | ${code(path)} | ${link(guideFor(a))} |\n`;
  }
  write('reference/http-api', { title: 'HTTP API', description: `All ${routes.length} factory, Belai and Pix routes, grouped by resource, with the guide that explains each.`, order: 4, checked: short('vdb-site') }, body);
}

// ── Console routes ─────────────────────────────────────────────────────────
{
  let body = 'Pages in the Vulnetix console that belong to Software Factory. All are under `https://www.vulnetix.com` and need you to be signed in.\n\n| Path | Explained in |\n|---|---|\n';
  for (const a of by('console')) body += `| [${code(a.value)}](https://www.vulnetix.com${a.value}) | ${link(guideFor(a))} |\n`;
  write('reference/console-routes', { title: 'Console pages', description: 'Every Software Factory page in the Vulnetix console and the guide that explains it.', order: 5, checked: short('website') }, body);
}

// ── Templates ──────────────────────────────────────────────────────────────
{
  const cats = groupBy(by('template'), (a) => a.detail?.category ?? 'Other');
  let body = 'Workflow templates you can start from. Using one creates a draft workflow (version 1) and starts nothing until you publish it. See ' + pageLink('workflows/templates', 'Templates') + ' for how they are ranked and filled in.\n';
  for (const [c, rows] of Object.entries(cats).sort(([a], [b]) => a.localeCompare(b))) {
    body += `\n## ${c}\n\n| Template | Id |\n|---|---|\n`;
    for (const a of rows) body += `| ${cell(a.detail?.name ?? a.value)} | <span id="${a.value}"></span>${code(a.value)} |\n`;
  }
  write('reference/templates', { title: 'Templates', nav: 'Template catalogue', description: `The ${by('template').length} workflow templates in the catalogue, by category.`, order: 6, checked: short('vdb-site') }, body);
}

// ── Voice tools ────────────────────────────────────────────────────────────
{
  let body = 'The tools Pix can call during a voice call. Pix speaks only figures these tools return. Tools that start or stop work need you to confirm a read-back first; see ' + pageLink('pix/calling-pix', 'Calling Pix') + '.\n\n| Tool | What it does |\n|---|---|\n';
  for (const a of by('voice-tool')) body += `| <span id="${a.value}"></span>${code(a.value)} | ${cell(a.detail?.description)} |\n`;
  write('reference/voice-tools', { title: 'Voice tools', description: `The ${by('voice-tool').length} tools Pix uses on a call, and what each one reads or does.`, order: 7, checked: short('website') }, body);
}

// ── Belai CLI ──────────────────────────────────────────────────────────────
{
  const flags = groupBy(by('cli-flag'), (a) => a.value.split(/ +-/)[0].trim() || 'belai');
  const subs = groupBy(by('cli-sub'), (a) => a.value.split(' ')[0]);
  let body = 'Every `belai` command, subcommand and flag. Flags take one dash or two (`-json` and `--json` are the same). Run `belai <command> -help` for the same list on your machine.\n\n## Commands\n\n| Command | Explained in |\n|---|---|\n';
  for (const a of by('cli-cmd')) body += `| ${code(a.value === 'belai' ? 'belai' : `belai ${a.value}`)} | ${link(guideFor(a))} |\n`;
  body += '\n## Subcommands\n';
  for (const [c, rows] of Object.entries(subs)) body += `\n### ${c}\n\n${rows.map((r) => code(r.value.split(' ').slice(1).join(' '))).join(', ')}\n`;
  body += '\n## Flags\n';
  for (const [s, rows] of Object.entries(flags).sort(([a], [b]) => (a === 'belai' ? -1 : b === 'belai' ? 1 : a.localeCompare(b)))) {
    body += `\n### ${s === 'belai' ? 'belai (top level)' : `belai ${s}`}\n\n| Flag | Default | What it does |\n|---|---|---|\n`;
    for (const a of rows) {
      const name = `-${a.value.split(/ +-/)[1]}`;
      const def = a.detail?.default;
      body += `| ${code(name)} | ${def && def !== '""' && def !== 'false' && def !== '0' ? code(def) : ''} | ${cell(a.detail?.usage)} |\n`;
    }
  }
  write('belai/cli-reference', { title: 'CLI reference', description: `Every belai command, subcommand and flag: ${by('cli-flag').length} flags across ${by('cli-cmd').length} commands.`, order: 90, checked: short('belai') }, body);
}

// ── Belai TUI commands ─────────────────────────────────────────────────────
{
  let body = 'Slash commands you type in the Belai terminal UI. Type `/` to see them with completion; `/help` lists them in the app.\n\n| Command | What it does | Explained in |\n|---|---|---|\n';
  for (const a of by('tui-cmd')) body += `| <span id="${a.value.slice(1)}"></span>${code(a.value)} | ${cell(a.detail?.description)} | ${link(guideFor(a))} |\n`;
  body += '\n## Keys\n\nKey bindings the TUI handles. What each one does depends on the view; see ' + pageLink('belai/tui', 'The terminal UI') + '.\n\n' + by('tui-key').map((a) => code(a.value)).join(', ') + '\n';
  write('belai/tui-commands', { title: 'TUI slash commands', nav: 'TUI commands', description: `All ${by('tui-cmd').length} slash commands and the key bindings of the Belai terminal UI.`, order: 91, checked: short('belai') }, body);
}

// ── Belai settings file ────────────────────────────────────────────────────
{
  const files = groupBy(by('belai-config'), (a) => a.value.split('.')[0]);
  let body = 'Keys Belai reads from its settings files, grouped by the part of the configuration they belong to. The guide pages explain what each group does; this page is the full list of names.\n';
  for (const [f, rows] of Object.entries(files)) {
    const ft = guideFor(rows[0]);
    body += `\n### ${f}\n\n${ft ? `Explained in ${link(ft)}.\n\n` : ''}${rows.map((r) => code(r.value.split('.').slice(1).join('.'))).join(', ')}\n`;
  }
  write('belai/settings-file', { title: 'Settings file reference', nav: 'Settings file', description: `The ${by('belai-config').length} keys Belai reads from its settings files, by group.`, order: 92, checked: short('belai') }, body);
}

// ── Forge capabilities ─────────────────────────────────────────────────────
// From vdb-site's forgecap table (api/internal/forgecap), the one source the
// console and the engine's refusals read too.
{
  const vdb = process.env.SF_SRC_VDB_SITE ?? join(root, '..', 'vdb-site');
  const file = join(vdb, 'api', 'internal', 'forgecap', 'testdata', 'forge-capabilities.json');
  if (existsSync(file)) {
    const doc = JSON.parse(readFileSync(file, 'utf8'));
    const kinds = doc.kinds.map((k) => k.id);
    const label = Object.fromEntries(doc.kinds.map((k) => [k.id, k.label]));
    const word = { native: 'Yes', emulated: 'Emulated', unavailable: 'Not available' };
    const at = (s) => (s ? `${word[s.level] ?? s.level}${s.note ? `: ${s.note}` : ''}` : '');
    let body = 'What each forge supports, emulates or lacks, from the factory\'s capability table. The console, the connect dialog and the engine\'s refusals read the same table: a step that needs something a forge lacks fails with `forge_capability_unavailable` and the reason below. Connecting each forge is in ' + pageLink('control/forge-connections', 'Forge connections') + '.\n\n';
    body += '| Forge | API dialect | A pull request is called |\n|---|---|---|\n';
    for (const k of doc.kinds) body += `| ${cell(k.label)} | ${code(k.dialect)} | ${cell(k.prNoun)} |\n`;
    body += '\n## Capabilities\n';
    for (const c of doc.capabilities) {
      body += `\n### ${cell(c.label)}\n\n<span id="${c.id}"></span>${cell(c.summary)} (${code(c.id)})\n\n| Forge | Support |\n|---|---|\n`;
      for (const k of kinds) body += `| ${cell(label[k])} | ${cell(at(c.support[k]))} |\n`;
    }
    body += '\n## Trigger events\n\nThe event names a trigger uses are GitHub\'s. Each forge\'s deliveries are translated into them; an event a forge cannot send never starts a run for its repositories.\n\n';
    body += `| Event | ${kinds.filter((k) => k !== 'github').map((k) => cell(label[k])).join(' | ')} |\n|---|${kinds.filter((k) => k !== 'github').map(() => '---').join('|')}|\n`;
    for (const [ev, sup] of Object.entries(doc.events)) {
      body += `| ${code(ev)} | ${kinds.filter((k) => k !== 'github').map((k) => cell(at(sup[k]))).join(' | ')} |\n`;
    }
    write('reference/forge-capabilities', { title: 'Forge capabilities', description: `What GitHub, GitHub Enterprise Server, Gitea, Forgejo and GitLab each support for the factory: ${doc.capabilities.length} capabilities and ${Object.keys(doc.events).length} trigger events.`, order: 8, checked: short('vdb-site') }, body);
  }
}

console.log('reference pages written');
